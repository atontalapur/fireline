"""Render docs/METHOD.md from docs/METHOD.template.md and validation.json.

The template holds placeholders such as ``{{pantanal.loyo_r}}`` or ``{{sentinel3.spearman_r}}``.
Each one is filled from ``PROCESSED_DIR/validation.json`` so every number in the method write-up
comes from the validation output, never from hand-typed values.

Placeholder forms:
    {{<region>.<metric>}}   value at validation["regions"][region][metric]
    {{sentinel3.<field>}}   value at validation["sentinel3"][field], falling back to
                            validation["regions"]["pantanal"]["sentinel3"][field]
    {{placebo.<field>}}     summary over every region's placebo entries: months (the placebo
                            dates), n, seam_ratio_min, seam_ratio_max, n_changepoint_sig
                            (change-point p below 0.05)
    {{method_version}}      validation["method_version"]

Nulls and missing values render as "n/a". With ``--pending`` every placeholder renders as
"pending", for use before validation.json exists. ``--check`` exits non-zero when the
committed METHOD.md differs from a fresh render.
"""

from __future__ import annotations

import argparse
import json
import logging
import math
import re
import sys
from pathlib import Path

import common

log = logging.getLogger("render_method")

DOCS_DIR = common.REPO_ROOT / "docs"
TEMPLATE_PATH = DOCS_DIR / "METHOD.template.md"
OUTPUT_PATH = DOCS_DIR / "METHOD.md"
VALIDATION_PATH = common.PROCESSED_DIR / "validation.json"

PENDING = "pending"
MISSING = "n/a"

# Metrics allowed in {{<region>.<metric>}} placeholders (validation.json contract, see A6).
REGION_METRICS = {
    "raw_bias",
    "harmonized_bias",
    "loyo_r",
    "loyo_nrmse",
    "forward_r",
    "seam_ratio",
    "changepoint_p",
    "changepoint_month",
    "peak_month_match",
}
# Fields allowed in {{sentinel3.<field>}} placeholders (A11).
SENTINEL3_FIELDS = {"spearman_r", "peak_month_match", "n_months"}
SENTINEL3_REGION = "pantanal"
# Fields allowed in {{placebo.<field>}} placeholders, summarized across regions.
PLACEBO_FIELDS = {"months", "n", "seam_ratio_min", "seam_ratio_max", "n_changepoint_sig"}
SIG_LEVEL = 0.05

PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.]+)\s*\}\}")
HEADER = (
    "<!-- Generated by pipeline/render_method.py from docs/METHOD.template.md and "
    "validation.json. Edit the template, then re-render. -->\n\n"
)

# Metric name -> how to format it.
RATIO_METRICS = {"raw_bias", "harmonized_bias", "seam_ratio", "seam_ratio_min", "seam_ratio_max"}
P_METRICS = {"changepoint_p"}
SHARE_METRICS = {"peak_month_match"}


def check_key(key: str) -> None:
    """Raise ValueError if a placeholder key is not a known form (catches template typos)."""
    parts = key.split(".")
    if parts == ["method_version"]:
        return
    if len(parts) == 2:
        head, leaf = parts
        if head == "sentinel3" and leaf in SENTINEL3_FIELDS:
            return
        if head == "placebo" and leaf in PLACEBO_FIELDS:
            return
        if head in common.REGIONS and leaf in REGION_METRICS:
            return
    raise ValueError(f"unknown placeholder {{{{{key}}}}}")


def join_words(items: list[str]) -> str:
    """'a', 'a and b', 'a, b and c'."""
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def placebo_summary(validation: dict, leaf: str):
    """Summarize placebo entries across all regions. None when there are none."""
    entries = [
        e
        for region in (validation.get("regions") or {}).values()
        if isinstance(region, dict)
        for e in region.get("placebo") or []
        if isinstance(e, dict)
    ]
    if leaf == "months":
        months = validation.get("placebo_months") or sorted(
            {e["month"] for e in entries if e.get("month")}
        )
        return join_words([str(m) for m in months]) if months else None
    if not entries:
        return None
    if leaf == "n":
        return len(entries)
    if leaf == "n_changepoint_sig":
        return sum(
            1
            for e in entries
            if isinstance(e.get("changepoint_p"), int | float) and e["changepoint_p"] < SIG_LEVEL
        )
    ratios = [
        float(e["seam_ratio"])
        for e in entries
        if isinstance(e.get("seam_ratio"), int | float) and math.isfinite(e["seam_ratio"])
    ]
    if not ratios:
        return None
    return min(ratios) if leaf == "seam_ratio_min" else max(ratios)


def lookup(validation: dict, key: str):
    """Return the raw value for a placeholder key, or None when it is absent."""
    parts = key.split(".")
    if parts == ["method_version"]:
        return validation.get("method_version")
    head, leaf = parts
    if head == "placebo":
        return placebo_summary(validation, leaf)
    if head == "sentinel3":
        block = validation.get("sentinel3")
        if not isinstance(block, dict):
            region = (validation.get("regions") or {}).get(SENTINEL3_REGION) or {}
            block = region.get("sentinel3")
        return block.get(leaf) if isinstance(block, dict) else None
    region = (validation.get("regions") or {}).get(head)
    return region.get(leaf) if isinstance(region, dict) else None


def format_value(value, metric: str) -> str:
    """Round a metric for prose. Ratios get an 'x' suffix, p-values a floor, shares a percent."""
    if value is None:
        return MISSING
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, str):
        return value
    if not isinstance(value, int | float):
        return MISSING
    v = float(value)
    if math.isnan(v) or math.isinf(v):
        return MISSING
    if metric in P_METRICS:
        if v < 0.001:
            return "< 0.001"
        return f"{v:.3f}" if v < 0.01 else f"{v:.2f}"
    if metric in SHARE_METRICS:
        pct = v * 100 if v <= 1 else v
        return f"{pct:.0f}%"
    if metric in RATIO_METRICS:
        return f"{v:.2f}x"
    if isinstance(value, int):
        return str(value)
    return f"{v:.2f}"


def render(template: str, validation: dict | None) -> str:
    """Fill every placeholder. validation=None renders all of them as 'pending'."""

    def fill(match: re.Match) -> str:
        key = match.group(1)
        check_key(key)
        if validation is None:
            return PENDING
        value = lookup(validation, key)
        if value is None:
            log.warning("no value for {{%s}}, writing %s", key, MISSING)
        return format_value(value, key.split(".")[-1])

    return HEADER + PLACEHOLDER.sub(fill, template)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--template", type=Path, default=TEMPLATE_PATH)
    parser.add_argument("--validation", type=Path, default=VALIDATION_PATH)
    parser.add_argument("--out", type=Path, default=OUTPUT_PATH)
    parser.add_argument(
        "--pending", action="store_true", help="render placeholders as 'pending' (no data needed)"
    )
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if --out differs from a fresh render"
    )
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    validation = None
    if not args.pending:
        if not args.validation.exists():
            sys.exit(f"{args.validation} not found. Run validate.py first, or pass --pending.")
        validation = json.loads(args.validation.read_text())

    text = render(args.template.read_text(), validation)

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            sys.exit(f"{args.out} is out of date. Re-run pipeline/render_method.py.")
        log.info("%s is up to date", args.out)
        return

    args.out.write_text(text)
    log.info("wrote %s", args.out)


if __name__ == "__main__":
    main()
