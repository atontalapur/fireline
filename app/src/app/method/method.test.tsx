import { readFileSync } from "node:fs";
import path from "node:path";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { REGION_PRESETS } from "@/lib/geo";
import { parseValidation } from "@/lib/method/validation";
import { MethodDoc } from "./method-doc";
import { ValidationView } from "./validation-table";

const repo = path.resolve(__dirname, "../../../..");
const mock = parseValidation(readFileSync(path.join(repo, "contracts/mock/validation.json"), "utf8"));

describe("ValidationView", () => {
  it("renders the mock as a captioned table with region names and n/a", () => {
    const html = renderToStaticMarkup(<ValidationView result={mock} presets={REGION_PRESETS} baseUrl={null} />);
    expect(html).toContain("<caption");
    expect(html).toContain("Mock data");
    expect(html).toContain('scope="col"');
    expect(html).toContain('scope="row"');
    for (const p of REGION_PRESETS) expect(html).toContain(p.name);
    expect(html).toContain("n/a");
    expect(html).toContain("&lt; 0.001");
    expect(html).not.toContain("<img");
  });

  it("shows figures only when a base URL is set", () => {
    const html = renderToStaticMarkup(
      <ValidationView result={mock} presets={REGION_PRESETS} baseUrl="https://storage.googleapis.com/b/public/v1/" />,
    );
    expect(html).toContain('src="https://storage.googleapis.com/b/public/v1/figures/seam_pantanal.png"');
    expect(html).toContain('src="https://storage.googleapis.com/b/public/v1/figures/scatter_pantanal.png"');
    expect(html.match(/<img/g)).toHaveLength(3);
  });

  it("explains missing and invalid files", () => {
    expect(
      renderToStaticMarkup(<ValidationView result={{ status: "missing" }} presets={REGION_PRESETS} baseUrl={null} />),
    ).toContain("not published yet");
    expect(
      renderToStaticMarkup(
        <ValidationView result={{ status: "invalid", error: "boom" }} presets={REGION_PRESETS} baseUrl={null} />,
      ),
    ).toContain("boom");
  });
});

describe("MethodDoc", () => {
  it("renders docs/METHOD.md with GFM tables and rewritten doc links", () => {
    const html = renderToStaticMarkup(
      <MethodDoc markdown={readFileSync(path.join(repo, "docs/METHOD.md"), "utf8")} />,
    );
    expect(html).toContain("<h1");
    expect(html).toContain("<table");
    expect(html).not.toContain("Generated by");
    expect(html).toContain('href="https://github.com/atontalapur/fireline/blob/main/docs/sentinel3.md"');
  });

  it("falls back to a summary with a pending note", () => {
    const html = renderToStaticMarkup(<MethodDoc markdown={null} />);
    expect(html).toContain("fire cell-days");
    expect(html).toContain("full method write-up is pending");
  });
});
